def _chunk(kind, body):
    return struct.pack(">I", len(body)) + kind + body + struct.pack(">I", zlib.crc32(kind + body))


class PixelBanner:
    def __init__(self, width, height, color):
        self.width = width
        self.height = height
        self.pixels = bytearray(bytes(color) * width * height)

    def box(self, x, y, w, h, color):
        stripe = bytes(color) * w
        for line in range(y, y + h):
            at = (line * self.width + x) * 3
            self.pixels[at : at + len(stripe)] = stripe

    def text(self, label, y, scale, color, *, x=None):
        if x is None:
            x = (self.width - (len(label) * 6 - 1) * scale) // 2
        for character in label:
            for row, bits in enumerate(FONT.get(character, FONT["?"]).split("/")):
                for column, bit in enumerate(bits):
                    if bit == "1":
                        self.box(x + column * scale, y + row * scale, scale, scale, color)
            x += 6 * scale

    def png(self):
        stride = self.width * 3
        scanlines = b"".join(
            b"\0" + self.pixels[at : at + stride] for at in range(0, len(self.pixels), stride)
        )
        return (
            b"\x89PNG\r\n\x1a\n"
            + _chunk(b"IHDR", struct.pack(">IIBBBBB", self.width, self.height, 8, 2, 0, 0, 0))
            + _chunk(b"IDAT", zlib.compress(scanlines))
            + _chunk(b"IEND", b"")
        )
